<h2>3. İşleme amaçları ve hukuki sebepler</h2>
<ul>
    <li><strong>Deneme ve üyelik hesabınızı açmak, hizmeti sunmak, paketinizi yönetmek</strong> — KVKK m.5/2-c (sözleşmenin kurulması veya ifası).</li>
    <li><strong>Fatura, vergi ve muhasebe yükümlülüklerini yerine getirmek</strong> — m.5/2-ç (hukuki yükümlülük).</li>
    <li><strong>Bilgi güvenliği, kötüye kullanımın ve sahte kayıtların önlenmesi, tekrar eden kayıtların tespiti</strong> — m.5/2-f (meşru menfaat).</li>
    <li><strong>İletişim ve destek taleplerinizi yanıtlamak</strong> — m.5/2-c ve m.5/2-f.</li>
    <li><strong>Kampanya, duyuru ve tanıtım iletileri göndermek</strong> — yalnızca ayrıca vereceğiniz açık rıza (m.5/1) ve 6563 sayılı Kanun kapsamında; rıza vermemeniz hizmetten yararlanmanızı etkilemez ve rızanızı dilediğiniz zaman geri alabilirsiniz.</li>
</ul>

<h2>4. Kişisel verilerin aktarılması</h2>
<p>Verileriniz satılmaz. Yalnızca amaçla sınırlı olarak ve gerekli olduğu ölçüde şu alıcı gruplarına aktarılabilir:</p>
<ul>
    <li>Barındırma (hosting), e-posta gönderimi ve yedekleme gibi altyapı hizmeti aldığımız tedarikçiler,</li>
    <li>Form güvenliği için kullandığımız Google reCAPTCHA hizmeti (Google; verilerin yurt dışında işlenmesi söz konusu olabilir),</li>
    <li>Yasal yükümlülük doğduğunda yetkili kamu kurum ve kuruluşları ile adli mercilere.</li>
</ul>
<p>Yurt dışına aktarım gerektiren hizmetlerde KVKK m.9 şartlarına uygun hareket edilir.</p>

<h2>5. Toplama yöntemi</h2>
<p>Verileriniz, web sitemizdeki deneme/üyelik ve iletişim formları, panel kullanımınız ve sunucu kayıtları aracılığıyla elektronik ortamda, otomatik veya kısmen otomatik yöntemlerle toplanır.</p>

<h2>6. Saklama süresi</h2>
<p>Verileriniz, işleme amacının gerektirdiği süre ve ilgili mevzuatta (Vergi Usul Kanunu, Türk Ticaret Kanunu vb.) öngörülen saklama süreleri boyunca tutulur; süre sonunda silinir, yok edilir veya anonim hale getirilir. Deneme sürecinin sonunda hesap açmaktan vazgeçerseniz silme talebinizi aşağıdaki kanaldan iletebilirsiniz.</p>

<h2>7. Prolyn'in “veri işleyen” rolü</h2>
<p>Prolyn paneline siz veya çalışanlarınız tarafından girilen müşteri, cari, randevu, kasa ve benzeri kayıtların (kendi müşterilerinizin kişisel verileri dahil) <strong>veri sorumlusu sizsiniz</strong>; Prolyn bu verileri yalnızca hizmeti sunmak amacıyla ve talimatlarınız doğrultusunda işleyen taraftır. Her firmanın verisi ayrı bir veritabanında tutulur. Kendi müşterilerinize karşı aydınlatma yükümlülüğü size aittir.</p>

<h2>8. KVKK m.11 kapsamındaki haklarınız</h2>
<p>Veri sahibi olarak şu haklara sahipsiniz:</p>
<ul>
    <li>Kişisel verilerinizin işlenip işlenmediğini öğrenme ve işlenmişse bilgi talep etme,</li>
    <li>İşlenme amacını ve amacına uygun kullanılıp kullanılmadığını öğrenme,</li>
    <li>Yurt içinde veya yurt dışında aktarıldığı üçüncü kişileri bilme,</li>
    <li>Eksik veya yanlış işlenmişse düzeltilmesini isteme,</li>
    <li>KVKK m.7 çerçevesinde silinmesini veya yok edilmesini isteme ve bu işlemlerin aktarıldığı üçüncü kişilere bildirilmesini isteme,</li>
    <li>İşlenen verilerin otomatik sistemlerle analiz edilmesi sonucu aleyhinize bir sonuç çıkmasına itiraz etme,</li>
    <li>Kanuna aykırı işlenmesi nedeniyle zarara uğramanız hâlinde zararın giderilmesini talep etme.</li>
</ul>

<h2>9. Başvuru yöntemi</h2>
<p>Haklarınıza ilişkin taleplerinizi, kimliğinizi doğrulayacak bilgilerle birlikte yukarıda yazılı KVKK başvuru e-posta adresine veya veri sorumlusunun adresine yazılı olarak iletebilirsiniz. Başvurunuz, talebin niteliğine göre en geç <strong>otuz gün</strong> içinde sonuçlandırılır. Cevabımızı yetersiz bulmanız hâlinde Kişisel Verileri Koruma Kurulu'na şikâyet hakkınız saklıdır.</p>
